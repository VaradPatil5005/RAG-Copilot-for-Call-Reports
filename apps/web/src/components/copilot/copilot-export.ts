"use client";

import type { ChatSession } from "./copilot-store";

/**
 * Downloads a string as a file in the user's browser.
 */
function triggerDownload(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Sanitize filename from title.
 */
function sanitizeFilename(title: string, ext: string): string {
  const base = title
    .replace(/[^a-zA-Z0-9_-]/g, "_")
    .replace(/_+/g, "_")
    .slice(0, 40)
    .trim() || "chat_session";
  return `${base}.${ext}`;
}

/**
 * Export full chat session as clean Markdown.
 */
export function exportToMarkdown(session: ChatSession): void {
  const dateStr = new Date(session.updatedAt).toLocaleString();
  let md = `# ${session.title}\n\n`;
  md += `*Generated by Tathyx Decision Intelligence Copilot*\n`;
  md += `*Date: ${dateStr}*\n\n`;
  md += `---\n\n`;

  session.turns.forEach((turn, idx) => {
    md += `## Turn ${idx + 1}: Query\n\n`;
    md += `> ${turn.query}\n\n`;
    md += `### Answer\n\n`;
    const answerText = turn.answer?.answer || "No answer recorded.";
    md += `${answerText}\n\n`;

    if (turn.evidence && turn.evidence.length > 0) {
      md += `### Grounded Sources & Evidence\n\n`;
      turn.evidence.forEach((item, sIdx) => {
        const title = item.section_path?.join(" › ") || item.document_id;
        md += `${sIdx + 1}. **${title}** (Page ${item.page_number || 1})\n`;
        md += `   - *Snippet*: "${item.snippet ? item.snippet.trim() : ""}"\n\n`;
      });
    }

    if (turn.modelName || turn.latencyMs) {
      md += `*Model: ${turn.modelName || "Primary"} | Latency: ${turn.latencyMs ? `${turn.latencyMs}ms` : "N/A"}*\n\n`;
    }
    md += `---\n\n`;
  });

  triggerDownload(md, sanitizeFilename(session.title, "md"), "text/markdown;charset=utf-8");
}

/**
 * Export full chat session as Microsoft Word (.doc / .docx compatible).
 */
export function exportToDocx(session: ChatSession): void {
  const dateStr = new Date(session.updatedAt).toLocaleString();
  let html = `
    <html xmlns:o='urn:schemas-microsoft-com:office:office' xmlns:w='urn:schemas-microsoft-com:office:word' xmlns='http://www.w3.org/TR/REC-html40'>
    <head>
      <meta charset='utf-8'>
      <title>${session.title}</title>
      <style>
        body { font-family: 'Calibri', 'Segoe UI', sans-serif; font-size: 11pt; line-height: 1.6; color: #1a1a1a; margin: 40px; }
        h1 { color: #0f172a; font-size: 20pt; border-bottom: 2px solid #0284c7; padding-bottom: 6px; margin-bottom: 4px; }
        .meta { font-size: 9pt; color: #64748b; margin-bottom: 24px; }
        .turn-box { background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 16px; margin-bottom: 20px; }
        .query-label { font-size: 9pt; font-weight: bold; color: #0284c7; text-transform: uppercase; margin-bottom: 4px; }
        .query { font-size: 13pt; font-weight: 600; color: #0f172a; margin-bottom: 12px; }
        .answer { font-size: 11pt; color: #334155; line-height: 1.7; margin-bottom: 16px; }
        .sources-title { font-size: 10pt; font-weight: bold; color: #475569; border-top: 1px solid #cbd5e1; padding-top: 10px; margin-top: 14px; }
        .source-item { font-size: 9.5pt; color: #475569; margin-bottom: 8px; }
        .source-badge { font-family: monospace; font-size: 8.5pt; background: #e0f2fe; color: #0369a1; padding: 2px 6px; border-radius: 4px; }
      </style>
    </head>
    <body>
      <h1>${session.title}</h1>
      <div class="meta">Tathyx Decision Intelligence Report · Generated: ${dateStr}</div>
  `;

  session.turns.forEach((turn, idx) => {
    const answerText = (turn.answer?.answer || "")
      .replace(/\n\n/g, "</p><p>")
      .replace(/\n/g, "<br/>");

    html += `
      <div class="turn-box">
        <div class="query-label">Question ${idx + 1}</div>
        <div class="query">${turn.query}</div>
        <div class="answer"><p>${answerText}</p></div>
    `;

    if (turn.evidence && turn.evidence.length > 0) {
      html += `<div class="sources-title">Grounded Evidence Sources:</div>`;
      turn.evidence.forEach((ev, sIdx) => {
        const title = ev.section_path?.join(" › ") || ev.document_id;
        html += `
          <div class="source-item">
            <span class="source-badge">[Source ${sIdx + 1}]</span>
            <strong>${title}</strong> (Page ${ev.page_number || 1})
            <div><em>"${(ev.snippet || "").slice(0, 200)}..."</em></div>
          </div>
        `;
      });
    }

    html += `</div>`;
  });

  html += `</body></html>`;

  triggerDownload(html, sanitizeFilename(session.title, "doc"), "application/msword");
}

